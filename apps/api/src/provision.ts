/**
 * First-customer onboarding spec from explicit operator input (G-16).
 * Used by `npm run api:provision` — never at server boot. Guards against
 * accidentally recreating the public demo identity as a "customer":
 * the demo slug, any @nile.demo address, and the public demo password are
 * all rejected. Passwords come from the operator's environment or are
 * generated by the CLI and shown once — never defaulted in code.
 */
export interface CustomerSpecInput {
  slug?: string;
  name?: string;
  managerEmail?: string;
  managerPassword?: string;
  managerName?: string;
  cashierEmail?: string;
  cashierPassword?: string;
  cashierName?: string;
  catalog?: NewCatalogItem[];
}

export function customerTenantSpec(input: CustomerSpecInput): TenantSpec {
  const slug = input.slug?.trim() ?? '';
  const name = input.name?.trim() ?? '';
  const managerEmail = input.managerEmail?.trim().toLowerCase() ?? '';
  if (!/^[a-z0-9][a-z0-9-]{1,48}[a-z0-9]$/.test(slug)) throw new Error('NILE_TENANT_SLUG is required (lowercase letters, digits, dashes; 3-50 chars)');
  if (slug === DEMO_TENANT.slug) throw new Error('Refusing to provision a customer with the demo slug (nile-demo). Choose a real slug.');
  if (!name) throw new Error('NILE_TENANT_NAME is required');
  if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(managerEmail)) throw new Error('NILE_MANAGER_EMAIL must be a valid email');
  if (managerEmail.endsWith('@nile.demo')) throw new Error('Refusing @nile.demo emails for a real customer.');
  const managerPassword = input.managerPassword ?? '';
  if (managerPassword.length < 12) throw new Error('Manager password must be at least 12 characters (or let the CLI generate one)');
  if (managerPassword === DEMO_PASSWORD) throw new Error('Refusing the public demo password for a real customer.');

  const accounts: TenantSpec['accounts'] = [{ role: 'branch-manager', email: managerEmail, name: input.managerName?.trim() || 'مدير فرع' }];
  const cashierEmail = input.cashierEmail?.trim().toLowerCase();
  if (cashierEmail) {
    if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(cashierEmail) || cashierEmail.endsWith('@nile.demo')) throw new Error('NILE_CASHIER_EMAIL must be a valid non-demo email');
    if (cashierEmail === managerEmail) throw new Error('Cashier and manager emails must differ');
    const cashierPassword = input.cashierPassword ?? '';
    if (cashierPassword.length < 12) throw new Error('Cashier password must be at least 12 characters (or let the CLI generate one)');
    if (cashierPassword === DEMO_PASSWORD) throw new Error('Refusing the public demo password for a real customer.');
    if (cashierPassword === managerPassword) throw new Error('Cashier and manager passwords must differ');
    accounts.push({ role: 'cashier', email: cashierEmail, password: cashierPassword, name: input.cashierName?.trim() || 'كاشير' });
  }
  return { slug, name, accounts, password: managerPassword, catalog: input.catalog ?? [] };
}
